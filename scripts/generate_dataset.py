def split_for_phrase(index: int) -> str:
    # Whole seed phrases are held out, not merely random paraphrases of one seed.
    if index in (20, 21):
        return "validation"
    if index in (22, 23, 24):
        return "test"
    return "train"


def main() -> None:
    rng = random.Random(SEED)
    rows = []
    seen = set()
    for category, phrases in ISSUES.items():
        count = 0
        while count < 1000:
            phrase_index = rng.randrange(len(phrases))
            phrase = phrases[phrase_index]
            prefix = rng.choice(PREFIXES)
            detail = rng.choice(DETAILS)
            ending = rng.choice(ENDINGS)
            if prefix.endswith(":"):
                text = f"{prefix} {phrase}; {detail}. {ending}"
            elif prefix == "Куда сообщить, если":
                text = f"{prefix} {phrase}? {detail.capitalize()}. {ending}"
            else:
                text = f"{prefix} {phrase}, {detail}. {ending}"
            if text in seen:
                continue
            seen.add(text)
            count += 1
            rows.append({
                "id": f"moscow-{category}-{count:04d}",
                "text_ru": text,
                "category": category,
                "split": split_for_phrase(phrase_index),
                "seed_phrase_group": f"{category}-{phrase_index:02d}",
                "city": "Москва",
                "origin": "synthetic_from_public_moscow_guides",
                "is_real_resident_message": False,
                "source_urls": SOURCES,
            })
    rng.shuffle(rows)
    with OUTPUT.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")
    digest = hashlib.sha256(OUTPUT.read_bytes()).hexdigest()
    print(f"{OUTPUT.name}: {len(rows)} rows, sha256={digest}")


if __name__ == "__main__":
    main()
